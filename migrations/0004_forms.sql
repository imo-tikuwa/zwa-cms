-- Contact forms. A form is shown on the pages that select it (posts.form_id);
-- the published Worker reads `forms` to validate a submission and inserts it
-- into `form_submissions`. The Turnstile widget is in settings
-- (forms.turnstile_sitekey).

CREATE TABLE forms (
  id              INTEGER PRIMARY KEY,
  name            TEXT NOT NULL,
  -- JSON array of {id, label, type: text|email|tel|textarea|checkbox, required}
  fields          TEXT NOT NULL DEFAULT '[]',
  submit_label    TEXT,
  success_message TEXT,
  created_at      TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ', 'now')),
  updated_at      TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ', 'now'))
);

ALTER TABLE posts ADD COLUMN form_id INTEGER REFERENCES forms (id) ON DELETE SET NULL;

CREATE TABLE form_submissions (
  id         INTEGER PRIMARY KEY,
  form_id    INTEGER NOT NULL REFERENCES forms (id) ON DELETE CASCADE,
  -- Generated by the page per form view; a resend of the same submission is ignored.
  nonce      TEXT NOT NULL UNIQUE,
  -- JSON array of {label, value}: a snapshot, so later form edits don't change it.
  data       TEXT NOT NULL,
  page_path  TEXT,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ', 'now')),
  read_at    TEXT
);

CREATE INDEX form_submissions_form ON form_submissions (form_id, created_at);
